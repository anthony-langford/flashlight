"""A single plain-language page for the owner to review: every causal map edge and every
drafted explainer, each with a place to note a decision. Generated, so it never drifts from the
YAML files that are the source of truth."""

from __future__ import annotations

from ingest.graph import Graph
from ingest.models import SeriesDef

HEADER = """# Review sheet

Generated from `graph/edges.yaml` and `catalogue/`. Do not edit this file, edit the YAML and
regenerate it with `uv run python -m ingest review`.

Everything here is a **draft** written from general reasoning. For each item, decide **keep**,
**change** (say how) or **remove**, then send your decisions back. Edges you approve are set to
`review: reviewed` and drawn solid on the map. A data check for every edge is in the app, on the
Causal map tab.

Nothing is wrong with an item just because it says draft. The point of this sheet is that
someone who knows the Toronto market reads each claim and says whether it holds.
"""


def _sign(sign: str) -> str:
    return "moves in the same direction" if sign == "+" else "moves in the opposite direction"


def render(graph: Graph, catalogue: list[SeriesDef]) -> str:
    labels = {n.id: n.label for n in graph.nodes}
    out = [HEADER, f"## 1. Causal map connections ({len(graph.edges)})\n"]
    for i, e in enumerate(graph.edges, start=1):
        out += [
            f"### 1.{i} {labels[e.source]} to {labels[e.target]}",
            "",
            f"- **Claim:** when **{labels[e.source]}** rises, "
            f"**{labels[e.target]}** {_sign(e.sign)}.",
            f"- **Why:** {e.rationale}",
            f"- **Typical timing:** {e.lag}",
            f"- **Confidence tag:** {e.confidence}",
            f"- **Status:** {e.review}",
            "- **Your decision:** [ ] keep   [ ] change   [ ] remove",
            "- **Notes:**",
            "",
        ]
    explained = [s for s in catalogue if s.explainer]
    out.append(f"## 2. Indicator explainers ({len(explained)})\n")
    for i, s in enumerate(sorted(explained, key=lambda s: s.id), start=1):
        ex = s.explainer
        assert ex is not None
        out += [
            f"### 2.{i} {s.title}",
            "",
            f"`{s.id}`",
            "",
            f"- **What it is:** {ex.what}",
            f"- **Why it matters for a buyer:** {ex.why_it_matters}",
            f"- **How to read it:** {ex.how_to_read}",
            "- **Your decision:** [ ] keep   [ ] change   [ ] remove",
            "- **Notes:**",
            "",
        ]
    return "\n".join(out)
